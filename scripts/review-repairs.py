"""CI regression evidence at the user's reported problem times.
Extracts actual encoded frames and short passages; no automatic visual approval.
"""
import os,sys,json,subprocess,hashlib,math
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
if os.environ.get('GITHUB_ACTIONS')!='true':raise RuntimeError('Formal review evidence is generated by GitHub Actions.')
root=Path(__file__).resolve().parents[1];movie=root/sys.argv[1]
meta=json.loads(Path(str(movie)+'.render.json').read_text());out=root/'output/repair-review';out.mkdir(exist_ok=True)
sections=[('shell-clearance',4,10),('canopy-and-contrast',14,20),('rotation-and-number',22.5,27),('native-glass',34,38.7),('subtitle-single-owner',46,54),('farewell-caption',78.3,91.8),('reconstruction-clearance',101,113),('corrected-text',119,132.9),('native-dawn-caption',135.258,151.4)]
font=ImageFont.truetype(str(root/'public/fonts/CJK.ttf'),18)
samples=[];clips=[]
for name,start,end in sections:
 for fraction in [.15,.5,.85]:
  time=start+(end-start)*fraction;frame=round((time-meta['sourceStart'])*meta['fps']);target=out/f'{name}-{fraction:.2f}.png'
  samples.append(dict(section=name,sourceTime=frame/meta['fps']+meta['sourceStart'],image=target.name))
frames=sorted({round((item['sourceTime']-meta['sourceStart'])*meta['fps']) for item in samples})
selection='+'.join(f'eq(n\\,{frame})' for frame in frames)
subprocess.run(['ffmpeg','-v','error','-y','-i',str(movie),'-vf','select='+selection,'-fps_mode','vfr','-frames:v',str(len(frames)),str(out/'encoded-%03d.png')],check=True)
byframe={frame:out/f'encoded-{i+1:03d}.png' for i,frame in enumerate(frames)}
for sample in samples:(out/sample['image']).write_bytes(byframe[round((sample['sourceTime']-meta['sourceStart'])*meta['fps'])].read_bytes())
for temporary in byframe.values():temporary.unlink()
for name,start,end in [('opening',0,20),('subtitle',46,55),('clearance',101,113),('dawn',135.258,151.4)]:
 target=out/(name+'.mp4')
 subprocess.run(['ffmpeg','-v','error','-y','-ss',str(start),'-i',str(movie),'-t',str(end-start),'-c:v','libx264','-preset','fast','-crf','19','-pix_fmt','yuv420p','-c:a','aac','-b:a','192k','-movflags','+faststart',str(target)],check=True)
 subprocess.run(['ffmpeg','-v','error','-i',str(target),'-f','null','-'],check=True)
 clips.append(dict(file=target.name,start=start,end=end,fullDecode='pass',sha256=hashlib.sha256(target.read_bytes()).hexdigest()))
# Preserve the true aspect ratio in individual PNGs; sheet thumbnails are 400x225.
sheet=Image.new('RGB',(1200,9*258),'#111923');draw=ImageDraw.Draw(sheet)
for i,sample in enumerate(samples):
 x=i%3*400;y=i//3*258;sheet.paste(Image.open(out/sample['image']).resize((400,225)),(x,y));draw.text((x+9,y+230),f"{sample['sourceTime']:.2f}s / {sample['section']}",font=font,fill='#dce7ec')
sheet.save(out/'reported-times.jpg',quality=96)
(out/'verification.json').write_text(json.dumps(dict(sourceCommit=meta['sourceCommit'],movie=movie.name,samples=samples,clips=clips,lyricSource='assets/lyric-corrections.json; community comparison, not officially verified',visualAcceptance='Requires actual inspection; successful extraction does not approve aesthetics or clearance.'),indent=2)+'\n')
